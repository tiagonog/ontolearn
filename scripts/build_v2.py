#!/usr/bin/env python3
"""build_v2.py — OntoLearn v2.0: axiomatic completion of ontolearn_v10.
Every addition is listed explicitly; nothing else is modified.
Reproducible: python3 build_v2.py <input_v10> <output.ttl> <output.owl>
"""
import sys, rdflib
from rdflib import OWL, RDF, RDFS, URIRef, BNode, Literal
from rdflib.collection import Collection

NS = rdflib.Namespace('http://www.ontolearn.com/ontologia#')
DCT = rdflib.Namespace('http://purl.org/dc/terms/')

src, out_ttl, out_owl = sys.argv[1], sys.argv[2], sys.argv[3]
g = rdflib.Graph()
with open(src, 'rb') as _fh:          # file handle: immune to spaces in paths
    g.parse(_fh, format='xml')
g.bind('', NS); g.bind('owl', OWL); g.bind('dcterms', DCT)
added = []

def add(t, why):
    if t not in g:
        g.add(t); added.append((t, why))

# ---- F0. Schema repair discovered by the partition audit:
# NP-Aplicar (:NiveisDeProficiencia) carries :descricao, but the declared
# union domain of :descricao omits NiveisDeProficiencia. Under the top-level
# partition this entails NP-Aplicar : owl:Nothing (global inconsistency).
# Minimal repair: extend the union to cover the class actually used in the ABox.
for _, _, dom_node in g.triples((NS.descricao, RDFS.domain, None)):
    for _, _, lst in g.triples((dom_node, OWL.unionOf, None)):
        Collection(g, lst).append(NS.NiveisDeProficiencia)
        added.append(((NS.descricao, RDFS.domain, '…∪ NiveisDeProficiencia'),
                      'F0 repair: domain union extended (defect exposed by partition)'))

# ---- F1. Taxonomic repair: Subjetiva was a disconnected island in v1.0
add((NS.Subjetiva, RDFS.subClassOf, NS.Questao), 'taxonomic repair (P04 recurrence)')

# ---- F2. Disjointness: KSA triad pairwise + Objetiva/Subjetiva
for a, b in [(NS.Conhecimento, NS.Habilidade), (NS.Conhecimento, NS.Atitude),
             (NS.Habilidade, NS.Atitude), (NS.Objetiva, NS.Subjetiva)]:
    add((a, OWL.disjointWith, b), 'disjointness family')

# ---- F2b. Top-level partition via owl:AllDisjointClasses
roots = [NS.UsuarioDoAva, NS.Competencia, NS.RecursoDeAprendizagem,
         NS.DesempenhoDoAprendiz, NS.Questao, NS.Avaliacao, NS.Curso,
         NS.NiveisDeProficiencia, NS.MilestoneDeAprendizagem,
         NS.TrajetoriasDeAprendizagem, NS.Conhecimento, NS.Habilidade, NS.Atitude]
b = BNode(); lst = BNode()
g.add((b, RDF.type, OWL.AllDisjointClasses))
Collection(g, lst, roots)
g.add((b, OWL.members, lst))
added.append(((b, RDF.type, OWL.AllDisjointClasses), 'top-level partition (13 roots)'))

# ---- F3. Existential participation constraints (superclass position; DL-safe)
def existential(cls, prop, filler, why):
    r = BNode()
    g.add((r, RDF.type, OWL.Restriction))
    g.add((r, OWL.onProperty, prop))
    g.add((r, OWL.someValuesFrom, filler))
    add((cls, RDFS.subClassOf, r), why)

existential(NS.Questao, NS.competenciasAvaliadas, NS.Competencia, 'existential: every question targets >=1 competency')
existential(NS.Avaliacao, NS.questoesIncluidas, NS.Questao, 'existential: every assessment includes >=1 question')
existential(NS.RecursoDeAprendizagem, NS.abordaCompetencia, NS.Competencia, 'existential: every resource addresses >=1 competency')
existential(NS.DesempenhoDoAprendiz, NS.proficienciaAtingida, NS.NiveisDeProficiencia, 'existential: every performance maps to a proficiency level')

# ---- F4. Role hierarchy (H): generic composition super-properties
for sup, subs in [
    (NS.temComponenteKSA, [NS.ehCompostoDeConhecimento, NS.ehCompostoDeHabilidade, NS.ehCompostoDeAtitude]),
    (NS.ehComponenteKSADe, [NS.compoeConhecimentoEm, NS.compoeHabilidadeEm, NS.compoeAtitudeEm]),
]:
    add((sup, RDF.type, OWL.ObjectProperty), 'role hierarchy: new super-property')
    for sb in subs:
        add((sb, RDFS.subPropertyOf, sup), 'role hierarchy (H)')
add((NS.temComponenteKSA, OWL.inverseOf, NS.ehComponenteKSADe), 'inverse pairing of new supers')
add((NS.temComponenteKSA, RDFS.domain, NS.Competencia), 'domain of super')
add((NS.temComponenteKSA, RDFS.label, Literal('tem componente KSA', lang='pt')), 'annotation')
add((NS.ehComponenteKSADe, RDFS.label, Literal('é componente KSA de', lang='pt')), 'annotation')

# ---- F5. Functional characteristic: one proficiency level per performance record
add((NS.proficienciaAtingida, RDF.type, OWL.FunctionalProperty), 'functional (F)')

# ---- F6. Version metadata (does NOT alter the ontology IRI — decision D-1 pending)
ont = URIRef('http://www.ontolearn.com/ontologia')
g.set((ont, OWL.versionInfo, Literal('2.0')))
g.add((ont, RDFS.comment, Literal(
    'OntoLearn v2.0 - axiomatic completion of v1.0: '
    'Subjetiva taxonomic repair; KSA + top-level disjointness; existential participation '
    'constraints; KSA role hierarchy; functional proficienciaAtingida. '
    'Generated by build_v2.py (released with the article).', lang='en')))

g.serialize(out_ttl, format='turtle')
g.serialize(out_owl, format='xml')
print(f'v2.0 written. Triples: {len(g)}  |  additions: {len(added)}')
for t, why in added:
    s, p, o = t
    fmt = lambda x: str(x).replace(str(NS), ':') if not isinstance(x, BNode) else '[]'
    print(f'  + {fmt(s)} {fmt(p)} {fmt(o)}   # {why}')
