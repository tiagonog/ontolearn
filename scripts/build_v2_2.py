#!/usr/bin/env python3
"""build_v2_2.py - OntoLearn v2.2: review-driven revision of v2.1.

Exactly one logical axiom is added (family F6, "level distinctness"):

    DisjointClasses(Lembrar Entender Aplicar Analisar AvaliarBloom Criar)

Rationale. v2.0 declared :proficienciaAtingida functional (family F5) and
described this as making contradictory proficiency assignments detectable.
Under OWL 2 semantics that description was wrong: OWL makes no unique-name
assumption, so a performance record linked to two level individuals entails
that the two individuals are THE SAME, not that the ontology is inconsistent.
The six Bloom-tier classes were not disjoint and the level individuals were
not declared different, so nothing contradicted that equality. F6 supplies the
missing premise: individuals of different tiers are necessarily different,
and a record carrying two tiers is therefore inconsistent.

Nothing else is modified. Blank nodes are relabelled canonically, so the
output is byte-for-byte reproducible from the same input.

Usage: python3 build_v2_2.py <ontolearn-v2.1.owl> <output.ttl> <output.owl>
"""
import sys
import rdflib
from rdflib import OWL, RDF, RDFS, URIRef, BNode, Literal
from rdflib.collection import Collection
from rdflib.compare import to_canonical_graph

NS = rdflib.Namespace('http://www.ontolearn.com/ontologia#')
DCT = rdflib.Namespace('http://purl.org/dc/terms/')
ONT = URIRef('http://www.ontolearn.com/ontologia')
TIERS = ['Lembrar', 'Entender', 'Aplicar', 'Analisar', 'AvaliarBloom', 'Criar']


def apply_f6(g):
    """Add F6 to graph g. Kept as a function so that the ablation can call the
    very same code that generates the release."""
    node, lst = BNode(), BNode()
    Collection(g, lst, [NS[t] for t in TIERS])
    g.add((node, RDF.type, OWL.AllDisjointClasses))
    g.add((node, OWL.members, lst))


def canonical(g):
    """Canonical blank-node labels (b1, b2, ...) and sorted output."""
    class SortedGraph(rdflib.Graph):
        def subjects(self, predicate=None, object=None, unique=False):
            return iter(sorted(set(super().subjects(predicate, object)), key=lambda x: x.n3()))

        def predicate_objects(self, subject=None, unique=False):
            return iter(sorted(set(super().predicate_objects(subject)),
                               key=lambda po: (po[0].n3(), po[1].n3())))

    canon = sorted(to_canonical_graph(g), key=lambda t: tuple(x.n3() for x in t))
    bnodes = sorted({x for t in canon for x in t if isinstance(x, BNode)}, key=lambda x: x.n3())
    rename = {b: BNode(f'b{i}') for i, b in enumerate(bnodes, 1)}
    cg = SortedGraph()
    for t in canon:
        cg.add(tuple(rename.get(x, x) for x in t))
    for prefix, ns in g.namespaces():
        cg.bind(prefix, ns, override=True)
    cg.bind('', NS)
    cg.bind('dcterms', DCT)
    return cg


if __name__ == '__main__':
    src, out_ttl, out_owl = sys.argv[1], sys.argv[2], sys.argv[3]
    g = rdflib.Graph()
    with open(src, 'rb') as fh:
        g.parse(fh, format='xml')
    n0 = len(g)

    # ---- F6. Level distinctness.
    apply_f6(g)

    # ---- Version metadata (the ontology IRI is unchanged).
    g.set((ONT, OWL.versionInfo, Literal('2.2')))
    g.remove((ONT, RDFS.comment, None))
    g.add((ONT, RDFS.comment, Literal(
        'OntoLearn v2.2 - revisão da v2.1: as seis classes de nível da Taxonomia de Bloom revisada '
        'passam a ser disjuntas entre si, de modo que um registro de desempenho com dois níveis '
        'distintos torna a base inconsistente (a funcionalidade de proficienciaAtingida, sozinha, '
        'apenas levava o raciocinador a identificar os dois níveis). Gerada por build_v2_2.py.',
        lang='pt')))
    g.add((ONT, RDFS.comment, Literal(
        'OntoLearn v2.2 - revision of v2.1: the six Bloom-tier classes are declared pairwise disjoint, '
        'so that a performance record carrying two different levels is inconsistent (the functional '
        'characteristic of proficienciaAtingida alone only led the reasoner to equate the two levels). '
        'Generated by build_v2_2.py.', lang='en')))

    cg = canonical(g)
    cg.serialize(out_ttl, format='turtle')
    cg.serialize(out_owl, format='xml')
    print(f'v2.2 written. Triples: {len(cg)} (input {n0})')
    print('  + DisjointClasses(' + ' '.join(TIERS) + ')   # F6 level distinctness')
    print('  ~ owl:versionInfo "2.2"; ontology rdfs:comment (pt, en) replaced')
